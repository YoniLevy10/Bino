const RCON = Uint8Array.from([0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36])

const T_C_KEY = Uint8Array.from([
  0xfa, 0xd3, 0x25, 0x72, 0x81, 0x29, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3a, 0xb4, 0x5a, 0x65,
])

function galoisMul2(value: number): number {
  return value & 0x80 ? ((value << 1) ^ 0x1b) & 0xff : (value << 1) & 0xff
}

function packUint64BE(num: number): Uint8Array {
  const result = new Uint8Array(8)
  let big = BigInt(num)
  const mask = BigInt(0xff)
  const eight = BigInt(8)
  for (let i = 7; i >= 0; i--) {
    result[i] = Number(big & mask)
    big >>= eight
  }
  return result
}

function bytesToHex(bytes: Uint8Array): string {
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('')
}

function aesEncryptDecrypt(stateBytes: Uint8Array, keyBytes: Uint8Array, isEncrypt: boolean): Uint8Array {
  if (stateBytes.length !== BLOCK_SIZE || keyBytes.length !== KEY_SIZE) {
    throw new Error('State and/or key are not 16 bytes')
  }
  const state = new Uint8Array(stateBytes)
  const key = new Uint8Array(keyBytes)
  aesEncDec(state, key, isEncrypt)
  return state
}

function aesEncDec(state: Uint8Array, key: Uint8Array, encrypt: boolean): void {
  if (encrypt) {
    for (let rnd = 0; rnd < 10; rnd++) {
      key[0] = (S_BOX[key[13]] ^ key[0] ^ RCON[rnd]) & 0xff
      key[1] = (S_BOX[key[14]] ^ key[1]) & 0xff
      key[2] = (S_BOX[key[15]] ^ key[2]) & 0xff
      key[3] = (S_BOX[key[12]] ^ key[3]) & 0xff
      for (let i = 4; i < KEY_SIZE; i++) {
        key[i] = (key[i] ^ key[i - 4]) & 0xff
      }
    }
    for (let i = 0; i < BLOCK_SIZE; i++) {
      state[i] = (state[i] ^ key[i]) & 0xff
    }
  }

  for (let rnd = 0; rnd < 10; rnd++) {
    if (encrypt) {
      for (let i = KEY_SIZE - 1; i > 3; i--) {
        key[i] = (key[i] ^ key[i - 4]) & 0xff
      }
      key[0] = (S_BOX[key[13]] ^ key[0] ^ RCON[9 - rnd]) & 0xff
      key[1] = (S_BOX[key[14]] ^ key[1]) & 0xff
      key[2] = (S_BOX[key[15]] ^ key[2]) & 0xff
      key[3] = (S_BOX[key[12]] ^ key[3]) & 0xff
    } else {
      for (let i = 0; i < BLOCK_SIZE; i++) {
        state[i] = S_BOX[state[i] ^ key[i]]
      }
      const buf1 = state[1]
      state[1] = state[5]
      state[5] = state[9]
      state[9] = state[13]
      state[13] = buf1

      const tmp1 = state[2]
      const tmp2 = state[6]
      state[2] = state[10]
      state[6] = state[14]
      state[10] = tmp1
      state[14] = tmp2

      const tmp = state[15]
      state[15] = state[11]
      state[11] = state[7]
      state[7] = state[3]
      state[3] = tmp
    }

    if ((rnd > 0 && encrypt) || (!encrypt && rnd < 9)) {
      for (let i = 0; i < 4; i++) {
        const base = i * 4
        if (encrypt) {
          const b1 = galoisMul2(galoisMul2(state[base] ^ state[base + 2]))
          const b2 = galoisMul2(galoisMul2(state[base + 1] ^ state[base + 3]))
          state[base] = (state[base] ^ b1) & 0xff
          state[base + 1] = (state[base + 1] ^ b2) & 0xff
          state[base + 2] = (state[base + 2] ^ b1) & 0xff
          state[base + 3] = (state[base + 3] ^ b2) & 0xff
        }
        const mix = state[base] ^ state[base + 1] ^ state[base + 2] ^ state[base + 3]
        const first = state[base]
        let buf3 = galoisMul2(state[base] ^ state[base + 1])
        state[base] = (state[base] ^ buf3 ^ mix) & 0xff
        buf3 = galoisMul2(state[base + 1] ^ state[base + 2])
        state[base + 1] = (state[base + 1] ^ buf3 ^ mix) & 0xff
        buf3 = galoisMul2(state[base + 2] ^ state[base + 3])
        state[base + 2] = (state[base + 2] ^ buf3 ^ mix) & 0xff
        buf3 = galoisMul2(state[base + 3] ^ first)
        state[base + 3] = (state[base + 3] ^ buf3 ^ mix) & 0xff
      }
    }

    if (encrypt) {
      const buf1 = state[13]
      state[13] = state[9]
      state[9] = state[5]
      state[5] = state[1]
      state[1] = buf1

      const t1 = state[10]
      const t2 = state[14]
      state[10] = state[2]
      state[14] = state[6]
      state[2] = t1
      state[6] = t2

      const tmp = state[3]
      state[3] = state[7]
      state[7] = state[11]
      state[11] = state[15]
      state[15] = tmp

      for (let i = 0; i < BLOCK_SIZE; i++) {
        state[i] = (INVERSE_S_BOX[state[i]] ^ key[i]) & 0xff
      }
    } else {
      key[0] = (S_BOX[key[13]] ^ key[0] ^ RCON[rnd]) & 0xff
      key[1] = (S_BOX[key[14]] ^ key[1]) & 0xff
      key[2] = (S_BOX[key[15]] ^ key[2]) & 0xff
      key[3] = (S_BOX[key[12]] ^ key[3]) & 0xff
      for (let i = 4; i < KEY_SIZE; i++) {
        key[i] = (key[i] ^ key[i - 4]) & 0xff
      }
    }
  }

  if (!encrypt) {
    for (let i = 0; i < BLOCK_SIZE; i++) {
      state[i] = (state[i] ^ key[i]) & 0xff
    }
  }
}

function step1(sessionToken: Uint8Array, phoneNumber: number): Uint8Array {
  const key = new Uint8Array(T_C_KEY)
  const phonePacked = packUint64BE(phoneNumber)
  for (let i = 0; i < 6; i++) {
    key[6 + i] = phonePacked[2 + i]
  }
  return aesEncryptDecrypt(sessionToken, key, true)
}

function step2(resultFromStep1: Uint8Array, timestampSec: number, timestampOffset: number): Uint8Array {
  const nextState = new Uint8Array(BLOCK_SIZE)
  const val16 = 0x0a0a
  nextState[1] = val16 & 0xff
  nextState[2] = (val16 >> 8) & 0xff
  const val32 = timestampSec + timestampOffset
  nextState[10] = (val32 >> 24) & 0xff
  nextState[11] = (val32 >> 16) & 0xff
  nextState[12] = (val32 >> 8) & 0xff
  nextState[13] = val32 & 0xff
  return aesEncryptDecrypt(nextState, resultFromStep1, false)
}

export function parsePalGateTokenType(raw: string | number | null | undefined): PalGateTokenTypeValue {
  if (typeof raw === 'number' && Number.isInteger(raw)) {
    if (raw === 0 || raw === 1 || raw === 2) return raw
  }
  const s = String(raw ?? '')
    .trim()
    .toLowerCase()
  if (s === '0' || s === 'sms') return PalGateTokenType.SMS
  if (s === '1' || s === 'primary') return PalGateTokenType.PRIMARY
  if (s === '2' || s === 'secondary') return PalGateTokenType.SECONDARY
  throw new Error('סוג טוקן PalGate לא תקין (sms/primary/secondary)')
}

export function generatePalGateDerivedToken(
  sessionToken: Uint8Array,
  phoneNumber: number,
  tokenType: PalGateTokenTypeValue,
  timestampSec: number | null = null,
  timestampOffset: number = TIMESTAMP_OFFSET
): string {
  if (sessionToken.length !== BLOCK_SIZE) {
    throw new Error('Session token must be 16 bytes')
  }
  const ts = timestampSec ?? Math.floor(Date.now() / 1000)
  const step2Key = step1(sessionToken, phoneNumber)
  const step2Result = step2(step2Key, ts, timestampOffset)

  const result = new Uint8Array(TOKEN_SIZE)
  if (tokenType === PalGateTokenType.SMS) result[0] = 0x01
  else if (tokenType === PalGateTokenType.PRIMARY) result[0] = 0x11
  else if (tokenType === PalGateTokenType.SECONDARY) result[0] = 0x21
  else throw new Error(`unknown token type: ${tokenType}`)

  const phonePacked = packUint64BE(phoneNumber)
  result.set(phonePacked.slice(2, 8), 1)
  result.set(step2Result, 7)
  return bytesToHex(result).toUpperCase()
}

export function sessionTokenFromHex(hex: string): Uint8Array {
  const cleaned = hex.trim().replace(/^0x/i, '')
  if (!/^[0-9a-fA-F]{32}$/.test(cleaned)) {
    throw new Error('Session token must be 32 hex chars (16 bytes)')
  }
  const out = new Uint8Array(16)
  for (let i = 0; i < 16; i++) {
    out[i] = parseInt(cleaned.slice(i * 2, i * 2 + 2), 16)
  }
  return out
}
